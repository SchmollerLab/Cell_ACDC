"""C12: repair cellacdc/_compat_moves.py for the tree after the C12 rewrite.

The tables are generated by the C3-C11 steps (state after C11). C12 then
changes what they point to:

- it removes the intermediate compat blocks, so the entries of the modules
  at new paths that had one (``cellacdc.gui.main_window.window``,
  ``cellacdc.measurements_viewer.viewer_utils``, ...) are dead;
- ``--drop-unused-imports`` removes imports that the runtime entries
  resolve through (the name table's ``runtime`` view: an import-bound old
  global resolves through the module that bound it after C11, e.g.
  ``cellacdc.measurements_viewer.load_position`` through the viewer
  window module, ``cellacdc.apps.widgets`` through
  ``shared/dialogs/generic.py``), so about 150 old names raised
  AttributeError.

This script keeps every entry whose home module still binds the name
(statically: module-level imports, assignments, defs and classes, also
inside if/try/with/for blocks; homes outside cellacdc and modules with a
module-level ``__getattr__`` are kept as they are) and points the others to
the module that defines the name (the name table's ``entries`` view, e.g.
``measurements_viewer/viewer_utils.py``, ``cellacdc.widgets`` for the old
``apps.widgets``). Names bound only as ``except ... as <name>`` targets
(never alive after the handler, e.g. ``gui.e``) are dropped. Modules
without a compat hook (``moved_module``/``package_compat`` or a
FORWARDERS source) lose their entries; they must be intermediate modules
of the name table. tests/test_compat.py checks the result in a fresh
interpreter (C13).

On tables that are already right this script changes nothing ("already
done"), so it stays harmless if run.py's C12 step learns to regenerate
the tables after the rewrite.
"""
import ast
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FIXUPS_DIR = os.path.dirname(HERE)
TOOLS_DIR = os.path.dirname(FIXUPS_DIR)
sys.path.insert(0, FIXUPS_DIR)
sys.path.insert(0, TOOLS_DIR)

import _fixuplib as F  # noqa: E402

PATH = 'cellacdc/_compat_moves.py'
HOOKS = ('moved_module(__name__', 'package_compat(__name__')


def module_file(repo, dotted):
    base = os.path.join(repo, *dotted.split('.'))
    for path in (base + '.py', os.path.join(base, '__init__.py')):
        if os.path.isfile(path):
            return path
    return None


def _store_names(target, names):
    for node in ast.walk(target):
        if isinstance(node, ast.Name) and isinstance(node.ctx, ast.Store):
            names.add(node.id)


def _collect(body, names, transient):
    for node in body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef,
                             ast.ClassDef)):
            names.add(node.name)
        elif isinstance(node, ast.Import):
            for alias in node.names:
                names.add(alias.asname or alias.name.split('.')[0])
        elif isinstance(node, ast.ImportFrom):
            for alias in node.names:
                if alias.name != '*':
                    names.add(alias.asname or alias.name)
        elif isinstance(node, ast.Assign):
            for target in node.targets:
                _store_names(target, names)
        elif isinstance(node, (ast.AnnAssign, ast.AugAssign)):
            _store_names(node.target, names)
        elif isinstance(node, (ast.For, ast.AsyncFor)):
            _store_names(node.target, names)
            _collect(node.body, names, transient)
            _collect(node.orelse, names, transient)
        elif isinstance(node, (ast.With, ast.AsyncWith)):
            for item in node.items:
                if item.optional_vars is not None:
                    _store_names(item.optional_vars, names)
            _collect(node.body, names, transient)
        elif isinstance(node, (ast.If, ast.While)):
            _collect(node.body, names, transient)
            _collect(node.orelse, names, transient)
        elif isinstance(node, ast.Try) or type(node).__name__ == 'TryStar':
            _collect(node.body, names, transient)
            for handler in node.handlers:
                if handler.name:
                    transient.add(handler.name)
                _collect(handler.body, names, transient)
            _collect(node.orelse, names, transient)
            _collect(node.finalbody, names, transient)
        elif isinstance(node, ast.Expr):
            for sub in ast.walk(node.value):
                if isinstance(sub, ast.NamedExpr):
                    _store_names(sub.target, names)


class Bindings:
    """Module-level names bound by the cellacdc modules of `repo`."""

    def __init__(self, repo):
        self.repo = repo
        self._cache = {}

    def get(self, dotted):
        if dotted not in self._cache:
            path = module_file(self.repo, dotted)
            if path is None:
                self._cache[dotted] = None
            else:
                text, _ = F._read(path)
                names, transient = set(), set()
                _collect(ast.parse(text).body, names, transient)
                self._cache[dotted] = (names, transient - names, text)
        return self._cache[dotted]

    def binds(self, home, attr):
        """True / False, or None for homes this check cannot decide
        (outside cellacdc, dynamic module __getattr__)."""
        if attr is None:
            return module_file(self.repo, home) is not None \
                if home.startswith('cellacdc.') else None
        if not (home == 'cellacdc' or home.startswith('cellacdc.')):
            return None
        found = self.get(home)
        if found is None:
            return False
        names, _, _ = found
        if attr in names:
            return True
        if '__getattr__' in names:
            return None
        # submodule of a package (``attr`` is a module)
        if module_file(self.repo, f'{home}.{attr}') is not None:
            return True
        return False

    def transient(self, home, attr):
        found = self.get(home)
        return found is not None and attr in found[1]

    def has_hook(self, dotted):
        found = self.get(dotted)
        return found is not None and any(h in found[2] for h in HOOKS)


def name_table(repo):
    import run
    plan = run.load_plan(repo)
    return plan.name_table(run.COMMITS[-1])


def repaired_moves(repo, moves, table):
    bindings = Bindings(repo)
    forwarded = set(moves['FORWARDERS'].values())
    intermediate = set(table.get('intermediate', {}))
    entries = table['entries']
    out = {}
    report = {'dropped_modules': [], 'retargeted': [], 'dropped': []}
    errors = []
    for module, names in sorted(moves['NAME_MOVES'].items()):
        if not (bindings.has_hook(module) or module in forwarded):
            if module not in intermediate:
                errors.append(f'{module}: no compat hook, but not an '
                              'intermediate module of the name table')
            report['dropped_modules'].append(module)
            continue
        kept = {}
        for name, (home, attr) in sorted(names.items()):
            if bindings.binds(home, attr) is not False:
                kept[name] = (home, attr)
                continue
            new = entries.get(module, {}).get(name)
            if new is not None and tuple(new) != (home, attr) and \
                    bindings.binds(*new) is not False:
                kept[name] = tuple(new)
                report['retargeted'].append(
                    f'{module}.{name}: {home}.{attr} -> {new[0]}.{new[1]}')
                continue
            if attr is not None and bindings.transient(home, attr):
                report['dropped'].append(
                    f'{module}.{name}: only an except-handler name of '
                    f'{home}')
                continue
            errors.append(f'{module}.{name}: {home}.{attr} is not bound '
                          f'there and the name table has no other home '
                          f'({new})')
        out[module] = kept
    return out, report, errors


def load_tables(text):
    namespace = {}
    exec(compile(text, PATH, 'exec'), namespace)
    return namespace


def replace_block(text, start_line, new_block):
    lines = text.split('\n')
    try:
        k = lines.index(start_line)
    except ValueError:
        raise F.FixupError(f'{PATH}: line {start_line!r} not found')
    end = lines.index('}', k) if not start_line.endswith('{}') else k
    return '\n'.join(lines[:k] + new_block.split('\n') + lines[end + 1:])


def main(repo):
    from acdc_refactor import shims
    full = os.path.join(repo, *PATH.split('/'))
    raw, eol = F._read(full)
    text = raw.replace('\r\n', '\n')
    moves = load_tables(text)
    table = name_table(repo)
    fixed, report, errors = repaired_moves(repo, moves, table)
    if errors:
        raise F.FixupError('cannot repair the compat tables:\n'
                           + '\n'.join(errors))
    if not any(report.values()):
        print(f'  {PATH}: already done')
        return
    start = next(line for line in text.split('\n')
                 if line.startswith('NAME_MOVES = '))
    new = replace_block(text, start, 'NAME_MOVES = '
                        + shims._fmt_nested(fixed))
    new = new.replace('(state after commit C11).',
                      '(state after commit C12).')
    if load_tables(new)['NAME_MOVES'] != fixed:
        raise F.FixupError(f'{PATH}: the rewritten table does not parse '
                           'back to the repaired one')
    F._write(full, new.replace('\n', eol))
    print(f'  {PATH}: dropped the entries of '
          f'{len(report["dropped_modules"])} modules without compat '
          f'hook, retargeted {len(report["retargeted"])} names, dropped '
          f'{len(report["dropped"])}')
    for key in ('dropped_modules', 'retargeted', 'dropped'):
        for line in report[key]:
            print(f'    {key}: {line}')
    items = [f'{PATH}::NAME_MOVES']
    F.log_change(PATH, items,
                 'compat tables repaired after the C12 rewrite: '
                 f'{len(report["dropped_modules"])} intermediate modules '
                 f'dropped, {len(report["retargeted"])} names retargeted '
                 'to their defining module, '
                 f'{len(report["dropped"])} except-handler names dropped')


if __name__ == '__main__':
    F.run(main)
